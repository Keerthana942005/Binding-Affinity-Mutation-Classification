def get_prop(d, aa, default=0):
    return d.get(aa, default)

def parse_mutations(mut_str):
    matches = re.findall(r'([A-Z])[A-Z]\d+([A-Z])', str(mut_str))
    return matches

def mutation_features(mut_str):
    muts = parse_mutations(mut_str)
    if not muts:
        return {'mean_dhydro':0,'mean_dcharge':0,'mean_dvol':0,
                'max_abs_dhydro':0,'max_abs_dcharge':0,'max_abs_dvol':0}
    dhydro_list, dcharge_list, dvol_list = [], [], []
    for from_aa, to_aa in muts:
        dhydro_list.append(get_prop(hydrophobicity, to_aa) - get_prop(hydrophobicity, from_aa))
        dcharge_list.append(get_prop(charge, to_aa) - get_prop(charge, from_aa))
        dvol_list.append(get_prop(volume, to_aa) - get_prop(volume, from_aa))
    return {
        'mean_dhydro': sum(dhydro_list)/len(dhydro_list),
        'mean_dcharge': sum(dcharge_list)/len(dcharge_list),
        'mean_dvol': sum(dvol_list)/len(dvol_list),
        'max_abs_dhydro': max(abs(x) for x in dhydro_list),
        'max_abs_dcharge': max(abs(x) for x in dcharge_list),
        'max_abs_dvol': max(abs(x) for x in dvol_list),
    }

def hamming_distance(s1, s2):
    s1, s2 = str(s1), str(s2)
    if len(s1) != len(s2):
        return abs(len(s1) - len(s2))
    return sum(a != b for a, b in zip(s1, s2))

def build_features_v2(df):
    feats = []
    for _, row in df.iterrows():
        row_feats = {
            'n_mutations': row['n_mutations'],
            'seq1_len': len(str(row['seq1_wt'])),
            'seq2_len': len(str(row['seq2_wt'])),
            'hamming1': hamming_distance(row['seq1_wt'], row['seq1_mut']),
            'hamming2': hamming_distance(row['seq2_wt'], row['seq2_mut']),
        }
        row_feats.update(mutation_features(row['Mutation(s)_cleaned']))
        feats.append(row_feats)
    return pd.DataFrame(feats)

