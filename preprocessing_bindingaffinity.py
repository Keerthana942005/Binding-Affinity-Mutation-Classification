from rdkit.Chem import rdFingerprintGenerator
import numpy as np

morgan_gen = rdFingerprintGenerator.GetMorganGenerator(radius=2, fpSize=1024)

def get_fingerprint(smi):
    mol = Chem.MolFromSmiles(smi)
    fp = morgan_gen.GetFingerprintAsNumPy(mol)
    return fp

fps = np.array([get_fingerprint(s) for s in df_dedup['Ligand SMILES']])
fp_df = pd.DataFrame(fps, columns=[f'fp_{i}' for i in range(fps.shape[1])])
df_dedup = pd.concat([df_dedup.reset_index(drop=True), fp_df], axis=1)

