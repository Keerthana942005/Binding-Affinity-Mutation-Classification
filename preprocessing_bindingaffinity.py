import numpy as np

# Remove censored/inequality values (e.g. ">10000")
df = df[~df['Ki (nM)'].astype(str).str.contains('<|>')]
df['Ki (nM)'] = pd.to_numeric(df['Ki (nM)'], errors='coerce')
df = df[df['Ki (nM)'].notna() & (df['Ki (nM)'] > 0)]

# Convert nM to Molar, then to pKi
df['pKi'] = -np.log10(df['Ki (nM)'] * 1e-9)

