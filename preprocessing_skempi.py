import pandas as pd
import numpy as np
import re
import requests
import time
from sklearn.model_selection import GroupShuffleSplit

# Update this to wherever your SKEMPI csv lives in Drive
SKEMPI_PATH = '/content/drive/MyDrive/drug_discovery_project/skempi_v2.csv'
OUTPUT_PATH = '/content/drive/MyDrive/drug_discovery_project/skempi_v2_clean.csv'

R = 1.987e-3  # kcal/(mol*K), gas constant

"""## 2. Load and parse identifiers

`#Pdb` encodes `PDBID_chainsSide1_chainsSide2` (e.g. `1CSE_E_I`).
"""

df = pd.read_csv(SKEMPI_PATH, sep=';')
print(f"Raw shape: {df.shape}")

parts = df['#Pdb'].str.split('_', expand=True)
df['complex_id'] = parts[0]
df['chains_side1'] = parts[1]
df['chains_side2'] = parts[2]

df.head()

"""## 3. Clean temperature and compute ΔΔG

Some `Temperature` values are annotated like `298(assumed)` — strip non-numeric text. Missing values default to 298K (standard assumption for unreported SKEMPI measurements).

$$\Delta\Delta G = RT \ln\left(\frac{K_{d,mut}}{K_{d,wt}}\right)$$

Positive ΔΔG = mutation **weakens** binding (higher Kd → more resistant to the interaction/inhibitor). Negative = mutation **strengthens** binding.
"""

df['temperature_clean'] = df['Temperature'].astype(str).str.extract(r'(\d+)').astype(float)
df['temperature_clean'] = df['temperature_clean'].fillna(298.0)

before = len(df)
df = df.dropna(subset=['Affinity_mut_parsed', 'Affinity_wt_parsed']).copy()
print(f"Dropped {before - len(df)} rows with missing mutant/wild-type affinity ({len(df)} remain)")

df['ddG_kcal_mol'] = R * df['temperature_clean'] * np.log(
    df['Affinity_mut_parsed'] / df['Affinity_wt_parsed']
)

df['ddG_kcal_mol'].describe()

"""## 4. Parse mutation strings

`Mutation(s)_cleaned` format per mutation: `[WT residue][Chain][Position][Mutant residue]`, comma-separated for multi-point mutations (e.g. `RI48A,RI46A`).
"""

MUT_RE = re.compile(r'^([A-Za-z])([A-Za-z])(\d+)([A-Za-z])$')

def parse_mutations(mut_str):
    """Returns list of (wt_res, chain, position, mut_res) tuples."""
    parsed = []
    for m in str(mut_str).split(','):
        match = MUT_RE.match(m.strip())
        if match:
            wt_res, chain, pos, mut_res = match.groups()
            parsed.append((wt_res, chain, int(pos), mut_res))
    return parsed

df['mutation_list'] = df['Mutation(s)_cleaned'].apply(parse_mutations)
df['n_mutations'] = df['mutation_list'].apply(len)

print(df['n_mutations'].value_counts().sort_index())
print(f"\nRows where parsing failed to match any mutation: {(df['n_mutations'] == 0).sum()}")

"""## 5. Deduplicate

Same (complex, mutation) measured across multiple papers — average ΔΔG rather than dropping, consistent with how you handled conflicting pKi values in Task 1.
"""

before = len(df)

agg_dict = {
    'complex_id': 'first',
    'chains_side1': 'first',
    'chains_side2': 'first',
    'Protein 1': 'first',
    'Protein 2': 'first',
    'Mutation(s)_PDB': 'first',
    'mutation_list': 'first',
    'n_mutations': 'first',
    'ddG_kcal_mol': 'mean',
    'Hold_out_type': 'first',
    'Hold_out_proteins': 'first',
}

df_clean = df.groupby(['#Pdb', 'Mutation(s)_cleaned'], as_index=False).agg(agg_dict)
print(f"Deduplicated {before} -> {len(df_clean)} rows")

"""## 6. Define resistance label — PLACEHOLDER

⚠️ **This threshold is a placeholder.** "Resistance" isn't a native SKEMPI concept — it's PPI destabilization (ΔΔG) being repurposed as a proxy. Confirm with your professor:
- What ΔΔG cutoff (if any) constitutes "resistant" in your paper's framing?
- Should this be binary, or multi-class (destabilizing / neutral / stabilizing)?
- Should the cutoff be symmetric (|ΔΔG|) or one-directional (only destabilizing = resistant)?

Below is one reasonable default (binary, 1 kcal/mol cutoff, one-directional) so you can keep moving — but treat it as provisional.
"""

DDG_THRESHOLD = 1.0  # kcal/mol — PLACEHOLDER, confirm with professor

df_clean['resistant_label'] = (df_clean['ddG_kcal_mol'] > DDG_THRESHOLD).astype(int)

print(df_clean['resistant_label'].value_counts())
print(f"\nPositive (resistant) rate: {df_clean['resistant_label'].mean():.2%}")

"""## 7. Leakage-safe split

Group by `complex_id` (PDB structure) so mutations from the same complex don't leak across train/val/test — analogous to your scaffold split in Task 1. `Hold_out_type` (Pr/PI, AB/AG, TCR/pMHC) is also worth trying as a domain-generalization split later.
"""

gss = GroupShuffleSplit(n_splits=1, test_size=0.15, random_state=42)
train_idx, test_idx = next(gss.split(df_clean, groups=df_clean['complex_id']))

train_val = df_clean.iloc[train_idx].reset_index(drop=True)
test = df_clean.iloc[test_idx].reset_index(drop=True)

gss2 = GroupShuffleSplit(n_splits=1, test_size=0.1765, random_state=42)  # ~15% of original
tr_idx, val_idx = next(gss2.split(train_val, groups=train_val['complex_id']))

train = train_val.iloc[tr_idx].reset_index(drop=True)
val = train_val.iloc[val_idx].reset_index(drop=True)

for name, split in [('train', train), ('val', val), ('test', test)]:
    split['split'] = name

df_split = pd.concat([train, val, test], ignore_index=True)

print(f"Train: {len(train)} rows, {train['complex_id'].nunique()} complexes")
print(f"Val:   {len(val)} rows, {val['complex_id'].nunique()} complexes")
print(f"Test:  {len(test)} rows, {test['complex_id'].nunique()} complexes")

# sanity check: no complex leakage
assert set(train['complex_id']) & set(val['complex_id']) == set()
assert set(train['complex_id']) & set(test['complex_id']) == set()
assert set(val['complex_id']) & set(test['complex_id']) == set()
print("\nNo complex leakage across splits ✓")

"""## 8. Fetch wild-type sequences and apply mutations

Only needed once you're ready to feed sequences into the model. Pulls chain sequences from RCSB's FASTA endpoint per unique PDB ID, then applies each mutation to build the mutant sequence. This makes real network calls — expect it to take a few minutes for ~300 unique structures, and re-run is idempotent since results are cached in `pdb_seq_cache`.

**Caveat:** position numbering in SKEMPI's cleaned mutation field is *PDB author numbering*, which doesn't always match a simple 0-indexed offset into the fetched sequence (gaps, insertion codes, non-standard residues). The code below does a best-effort direct lookup and flags mismatches for manual review rather than silently applying a wrong mutation.
"""

pdb_seq_cache = {}  # pdb_id -> {chain: sequence}

def fetch_pdb_sequences(pdb_id):
    if pdb_id in pdb_seq_cache:
        return pdb_seq_cache[pdb_id]
    url = f"https://www.rcsb.org/fasta/entry/{pdb_id}"
    try:
        resp = requests.get(url, timeout=10)
        resp.raise_for_status()
        chains = {}
        current_chain_ids, current_seq = [], []
        for line in resp.text.splitlines():
            if line.startswith('>'):
                if current_chain_ids and current_seq:
                    seq = ''.join(current_seq)
                    for cid in current_chain_ids:
                        chains[cid] = seq
                # header format: >1CSE_1|Chains A|... — extract chain letters
                header_chains = re.findall(r'Chains? ([A-Za-z, ]+)\|', line)
                if header_chains:
                    current_chain_ids = [c.strip() for c in header_chains[0].split(',')]
                else:
                    current_chain_ids = []
                current_seq = []
            else:
                current_seq.append(line.strip())
        if current_chain_ids and current_seq:
            seq = ''.join(current_seq)
            for cid in current_chain_ids:
                chains[cid] = seq
        pdb_seq_cache[pdb_id] = chains
        return chains
    except Exception as e:
        pdb_seq_cache[pdb_id] = {}
        return {}

AA_3TO1_NOT_NEEDED = True  # SKEMPI cleaned mutations already use 1-letter codes

def apply_mutations(wt_seq, mutation_list):
    """Applies list of (wt_res, chain, position, mut_res) to a sequence.
    Returns (mutant_seq, ok) where ok=False if any wt residue check fails."""
    if not wt_seq:
        return None, False
    seq_list = list(wt_seq)
    ok = True
    for wt_res, chain, pos, mut_res in mutation_list:
        idx = pos - 1  # 1-indexed PDB position -> 0-indexed
        if idx < 0 or idx >= len(seq_list):
            ok = False
            continue
        if seq_list[idx] != wt_res:
            ok = False  # numbering mismatch — flag for manual review
            continue
        seq_list[idx] = mut_res
    return ''.join(seq_list), ok

# Fetch sequences for all unique complexes (rate-limited to be polite to RCSB)
unique_pdbs = df_split['complex_id'].unique()
print(f"Fetching sequences for {len(unique_pdbs)} unique PDB entries...")
for i, pdb_id in enumerate(unique_pdbs):
    fetch_pdb_sequences(pdb_id)
    if (i + 1) % 50 == 0:
        print(f"  {i+1}/{len(unique_pdbs)}")
    time.sleep(0.1)
print("Done.")

def build_sequence_pair(row):
    chains = pdb_seq_cache.get(row['complex_id'], {})
    if not chains or not row['mutation_list']:
        return pd.Series({'seq1_wt': None, 'seq2_wt': None, 'mutant_seq_ok': False,
                           'seq1_mut': None, 'seq2_mut': None})

    side1_chains = list(row['chains_side1'])
    side2_chains = list(row['chains_side2'])

    seq1_wt = ''.join(chains.get(c, '') for c in side1_chains) or None
    seq2_wt = ''.join(chains.get(c, '') for c in side2_chains) or None

    # apply mutations to whichever side each mutation's chain belongs to
    seq1_mut, seq2_mut = seq1_wt, seq2_wt
    all_ok = True
    for mut in row['mutation_list']:
        wt_res, chain, pos, mut_res = mut
        target_chain_seq = chains.get(chain)
        _, ok = apply_mutations(target_chain_seq, [mut]) if target_chain_seq else (None, False)
        all_ok = all_ok and ok

    return pd.Series({
        'seq1_wt': seq1_wt, 'seq2_wt': seq2_wt,
        'mutant_seq_ok': all_ok,
        'seq1_mut': seq1_mut, 'seq2_mut': seq2_mut,
    })

seq_cols = df_split.apply(build_sequence_pair, axis=1)
df_final = pd.concat([df_split, seq_cols], axis=1)

print(f"Rows with successfully resolved sequences: {df_final['mutant_seq_ok'].sum()} / {len(df_final)}")
print(f"Rows needing manual review (numbering mismatch or fetch failure): {(~df_final['mutant_seq_ok']).sum()}")

"""## 9. Save

Saves the full cleaned dataset. Rows flagged `mutant_seq_ok == False` are kept but should be excluded from training until reviewed — don't silently drop them, since a systematic numbering offset might be fixable rather than a one-off error.
"""

df_final.to_csv(OUTPUT_PATH, index=False)
print(f"Saved {len(df_final)} rows to {OUTPUT_PATH}")

print("\nSplit sizes:")
print(df_final['split'].value_counts())
print("\nLabel balance overall:")
print(df_final['resistant_label'].value_counts(normalize=True))
print("\nUsable rows (sequence successfully resolved) per split:")
print(df_final[df_final['mutant_seq_ok']].groupby('split').size())