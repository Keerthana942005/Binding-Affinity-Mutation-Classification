import pandas as pd
import numpy as np

train_df = pd.read_csv('/content/drive/MyDrive/bindingdb_train_final.csv')
test_df = pd.read_csv('/content/drive/MyDrive/bindingdb_test_final.csv')

print("Train shape:", train_df.shape)
print("Test shape:", test_df.shape)

non_feature_cols = ['Ligand SMILES', 'UniProt (SwissProt) Primary ID of Target Chain 1',
                     'BindingDB Target Chain Sequence 1', 'Target Name',
                     'Target Source Organism According to Curator or DataSource', 'pKi']

feature_cols = [c for c in train_df.columns if c not in non_feature_cols]

X_train = train_df[feature_cols].values
y_train = train_df['pKi'].values
X_test = test_df[feature_cols].values
y_test = test_df['pKi'].values

print("Number of features:", len(feature_cols))
print(X_train.shape, X_test.shape)

import re

AMINO_ACIDS = list("ACDEFGHIKLMNPQRSTVWY")

def get_protein_features(seq):
    seq = str(seq).upper()
    length = len(seq)
    if length == 0:
        return [0]*21
    counts = [seq.count(aa) / length for aa in AMINO_ACIDS]  # amino acid composition (fractions)
    return [length] + counts

protein_feat_cols = ['seq_length'] + [f'aac_{aa}' for aa in AMINO_ACIDS]

train_protein_feats = train_df['BindingDB Target Chain Sequence 1'].apply(get_protein_features)
test_protein_feats = test_df['BindingDB Target Chain Sequence 1'].apply(get_protein_features)

train_protein_df = pd.DataFrame(train_protein_feats.tolist(), columns=protein_feat_cols)
test_protein_df = pd.DataFrame(test_protein_feats.tolist(), columns=protein_feat_cols)

print(train_protein_df.shape, test_protein_df.shape)
train_protein_df.head()

X_train_full = np.hstack([X_train, train_protein_df.values])
X_test_full = np.hstack([X_test, test_protein_df.values])

print("New feature count:", X_train_full.shape[1], "(was", X_train.shape[1], ")")

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

X_tr, X_val, y_tr, y_val = train_test_split(
    X_train_full, y_train, test_size=0.15, random_state=42
)

scaler2 = StandardScaler()
X_tr_scaled = scaler2.fit_transform(X_tr)     # fit only on the train part
X_val_scaled = scaler2.transform(X_val)
X_test_full_scaled = scaler2.transform(X_test_full)

import tensorflow as tf
from tensorflow import keras

tf.random.set_seed(42)   # for reproducible comparisons across runs

model2 = keras.Sequential([
    keras.layers.Input(shape=(X_tr_scaled.shape[1],)),
    keras.layers.Dense(256, activation='relu', kernel_regularizer=keras.regularizers.l2(1e-4)),
    keras.layers.BatchNormalization(),
    keras.layers.Dropout(0.4),

    keras.layers.Dense(128, activation='relu', kernel_regularizer=keras.regularizers.l2(1e-4)),
    keras.layers.BatchNormalization(),
    keras.layers.Dropout(0.4),

    keras.layers.Dense(64, activation='relu', kernel_regularizer=keras.regularizers.l2(1e-4)),
    keras.layers.Dropout(0.3),

    keras.layers.Dense(1)
])

model2.compile(
    optimizer=keras.optimizers.Adam(learning_rate=5e-4),
    loss='mse',
    metrics=['mae']
)
model2.summary()

early_stop2 = keras.callbacks.EarlyStopping(
    monitor='val_loss', patience=30, restore_best_weights=True
)

reduce_lr = keras.callbacks.ReduceLROnPlateau(
    monitor='val_loss', factor=0.5, patience=10, min_lr=1e-6
)

history2 = model2.fit(
    X_tr_scaled, y_tr,
    validation_data=(X_val_scaled, y_val),
    epochs=100,
    batch_size=256,
    callbacks=[early_stop2, reduce_lr],
    verbose=1
)

from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score
from scipy.stats import pearsonr, spearmanr

y_pred2 = model2.predict(X_test_full_scaled).flatten()

rmse2 = np.sqrt(mean_squared_error(y_test, y_pred2))
mae2 = mean_absolute_error(y_test, y_pred2)
r2_2 = r2_score(y_test, y_pred2)
pearson2, _ = pearsonr(y_test, y_pred2)
spearman2, _ = spearmanr(y_test, y_pred2)

print("=== DNN (Ligand + Protein) ===")
print(f"RMSE: {rmse2:.3f}  MAE: {mae2:.3f}  R2: {r2_2:.3f}  Pearson r: {pearson2:.3f}  Spearman r: {spearman2:.3f}")

from sklearn.model_selection import train_test_split
import xgboost as xgb

X_tr, X_val, y_tr, y_val = train_test_split(X_train_full, y_train, test_size=0.15, random_state=42)

xgb_model2 = xgb.XGBRegressor(
    n_estimators=1000,
    max_depth=6,
    learning_rate=0.05,
    subsample=0.8,
    colsample_bytree=0.8,
    random_state=42,
    n_jobs=-1,
    early_stopping_rounds=20,
    eval_metric='rmse'
)

xgb_model2.fit(
    X_tr, y_tr,
    eval_set=[(X_val, y_val)],
    verbose=True
)

y_pred_xgb2 = xgb_model2.predict(X_test_full)

rmse_xgb2 = np.sqrt(mean_squared_error(y_test, y_pred_xgb2))
mae_xgb2 = mean_absolute_error(y_test, y_pred_xgb2)
r2_xgb2 = r2_score(y_test, y_pred_xgb2)
pearson_xgb2, _ = pearsonr(y_test, y_pred_xgb2)

print("=== XGBoost (Ligand + Protein) ===")
print(f"RMSE: {rmse_xgb2:.3f}, MAE: {mae_xgb2:.3f}, R²: {r2_xgb2:.3f}, Pearson r: {pearson_xgb2:.3f}")

final_results = pd.DataFrame({
    'Model': ['DNN (Ligand + Protein)', 'XGBoost (Ligand + Protein)'],
    'RMSE': [rmse2, rmse_xgb2],
    'MAE': [mae2, mae_xgb2],
    'R2': [r2_2, r2_xgb2],
    'Pearson_r': [pearson2, pearson_xgb2]
})
print(final_results)
final_results.to_csv('/content/drive/MyDrive/final_model_comparison.csv', index=False)

import matplotlib.pyplot as plt

